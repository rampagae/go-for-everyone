package main

import "fmt"

// История про Машу и яблоки: переменные + цикл

func main() {
    apples := 5 // у Маши 5 яблок

    // Перебираем от 1 до apples и сообщаем, сколько яблок «посчитали»
    for i := 1; i <= apples; i++ {
        fmt.Println("Посчитали яблоко №", i)
    }

    // Пример: выводим только чётные номера (continue пропускает нечётные)
    for i := 1; i <= apples; i++ {
        if i%2 != 0 {
            continue
        }
        fmt.Println("Чётное яблоко №", i)
    }

    // Под капотом:
    // - i и apples — переменные в памяти (обычно стек)
    // - на каждой итерации проверяется условие i <= apples
    // - при continue выполняется переход к следующей итерации
    // - fmt печатает результат в stdout
}


