package main

import "fmt"

// Пример: переменные + условия + цикл + простая функция

// isEven возвращает true, если число чётное
func isEven(n int) bool {
    return n%2 == 0
}

func main() {
    start := 1
    end := 10

    // Перебираем числа от start до end и печатаем только чётные
    for i := start; i <= end; i++ {
        if isEven(i) { // условие использует функцию
            fmt.Println("Чётное:", i)
        }
    }

    // Под капотом:
    // - start, end, i — переменные в памяти; i обновляется на каждой итерации
    // - if читает значение i и решает, печатать ли число
    // - вызов isEven создаёт стековый фрейм и возвращает bool
    // - fmt выводит текст в stdout
}


