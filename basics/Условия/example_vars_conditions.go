package main

import "fmt"

// Переменные + условия, с пояснением «под капотом» в комментариях.

func main() {
    // Объявляем переменные: им выделяются ячейки в памяти (обычно стек)
    apples := 5       // количество яблок (int)
    eaten := 2        // откушенные яблоки (int)
    part := 0.25      // доля яблока (float64)
    label := "green"  // метка, строка (string)

    // Меняем состояние: записываем новые значения в ячейки памяти
    apples = apples - eaten

    // Условие читает значения из ячеек памяти и принимает решение
    if apples > 0 && part > 0 {
        fmt.Println("Есть целые и частичные яблоки")
    } else if apples > 0 {
        fmt.Println("Есть только целые яблоки")
    } else {
        fmt.Println("Целых яблок нет")
    }

    // switch сравнивает значение с вариантами сверху вниз
    switch label {
    case "red":
        fmt.Println("красное яблоко")
    case "green":
        fmt.Println("зелёное яблоко")
    default:
        fmt.Println("другая метка")
    }

    // Под капотом:
    // - переменные лежат в памяти; условные выражения читают их текущие значения
    // - if/else и switch компилируются в ветвления: выполняется только пройденная ветка
    // - fmt пишет результат в stdout, ОС показывает его в терминале
}


