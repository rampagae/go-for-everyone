package main

import "fmt"

// Переменные — это именованные хранилища данных. Их значения можно менять.
// Ниже показаны разные типы переменных и способы их объявления.
// Пакет fmt — наш «ящик с инструментами» для вывода в консоль и форматирования.

func main() {
    // Короткое объявление (внутри функции): одновременно объявляет и присваивает значение
    apples := 5 // целое число: количество яблок

    // Общая форма объявления (тип может выводиться):
    var eaten int = 2 // целое число: откушенные яблоки

    // Число с плавающей запятой — доля яблока
    var part float64 = 0.5

    // Строка — текст, например, название книги
    bookTitle := "Programming with Go"

    // Логическое значение — да/нет: осталось ли яблоко целым?
    var isWhole bool = apples == 1 && part == 0

    // Можно менять значения переменных позже
    apples = apples - eaten // стало меньше целых яблок

    // Печатаем значения с помощью fmt — как техник, который сообщает результат работы
    fmt.Println("Яблоки целые:", apples)
    fmt.Println("Откушенные яблоки:", eaten)
    fmt.Println("Доля яблока:", part)
    fmt.Println("Название книги:", bookTitle)
    fmt.Println("Целое ли яблоко:", isWhole)
}